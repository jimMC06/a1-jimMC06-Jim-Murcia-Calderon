const songDialog = document.querySelector<HTMLDialogElement>("#song-dialog")!;

const songSelect = document.querySelector<HTMLSelectElement>("#song-select")!;

const audioStatus = d3.select("#audio-status");
const customSongInput = document.querySelector<HTMLInputElement>("#custom-song")!;
let customSongUrl: string | null = null;

// Open the cassette popup
d3.select("#cassette-button").on("click", () => {
    songDialog.showModal();
});

// Close without changing the song
d3.select("#close-dialog-button").on("click", () => {
    songDialog.close();
});


// Load up custom song
customSongInput.addEventListener("change", () => {
    const file = customSongInput.files?.[0];
    if (!file) { //Chatgpt helped me debug an issue I had with the file variable, I just forgot to check it
        return;
    }

    audio.pause();

    const previousUrl = customSongUrl; //THIS WAS CHATGPT, MY IMPLEMTATION DID NOT REMOVE/UNLOAD OLD SONGS

    customSongUrl = URL.createObjectURL(file);
    audio.src = customSongUrl;
    audio.load();

    if (previousUrl !== null) { // THIS WAS CHATGPT, MY IMPLEMTATION DID NOT REMOVE/UNLOAD OLD SONGS
        URL.revokeObjectURL(previousUrl);
    }
    
    songTitle.text(file.name);
    audioStatus.text("Cassette loaded. Press Play.");

    customSongInput.value = "";
    songDialog.close();
});


// Load the selected song without starting playback
d3.select("#load-song-button").on("click", () => {
    audio.pause();

    audio.src = `${import.meta.env.BASE_URL}audio/${songSelect.value}`; //Chatgpt added this
    audio.load();


    if (customSongUrl !== null) { //Delete custom loaded song when selecting a different song
        URL.revokeObjectURL(customSongUrl);
        customSongUrl = null;
    }

    songTitle.text(songSelect.value);
    audioStatus.text("Cassette loaded. Press Play.");

    songDialog.close();
});

// Play or resume the selected song
d3.select("#play-button").on("click", async () => {
    try {
        await playAudio();
    } catch (error) {
        audioStatus.text(
            error instanceof Error
                ? error.message
                : "Unable to start playback."
        );
    }
});

// Pause without resetting the song position
d3.select("#pause-button").on("click", () => {
    audio.pause();
});

// Status messages connected to the actual player
audio.addEventListener("playing", () => {
    audioStatus.text("Playing.");
});

audio.addEventListener("pause", () => {
    audioStatus.text("Paused.");
});

audio.addEventListener("ended", () => {
    audioStatus.text("Song finished.");
});

audio.addEventListener("error", () => {
    audioStatus.text("Could not play this file. Choose another MP3.");
});


/*
    ------------------------------------------------
                Animation for Audio bars            
    ------------------------------------------------
*/

const heightScale = d3.scaleLinear()
    .domain([0, 255])
    .range([0, graphHeight]);

d3.timer(() => {
    const frequencyData = readFrequencyData();

    for (let barIndex = 0; barIndex < barCount; barIndex++) {
        const startIndex = barIndex * 2;
        const total = frequencyData[startIndex] + frequencyData[startIndex + 1];

        barLevels[barIndex] = total / 2;
    }

    bars.data(barLevels)
        .attr("height", (level) => heightScale(level))
        .attr("y", (level) => graphHeight - heightScale(level));
});


