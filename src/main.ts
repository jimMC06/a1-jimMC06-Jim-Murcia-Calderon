// The actual equalizer graph/visual, when nothing selected nothing appears, when song is selected it animates to the song
export const equalizer = svg.append("g")
    .attr("transform", "translate(312,230)");

const barCount = 32;
const graphWidth = 400;
const graphHeight = 110;
const barSpacing = graphWidth / barCount;

const barLevels = new Array<number>(barCount).fill(0);

const bars = equalizer.selectAll<SVGRectElement, number>("rect")
    .data(barLevels)
    .join("rect")
    .attr("x", (level, index) => index * barSpacing)
    .attr("y", graphHeight)
    .attr("width", barSpacing - 2)
    .attr("height", 0)
    .attr("fill", "#00cc66");

